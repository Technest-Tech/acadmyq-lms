it('keeps a package left open for a student removed the old way off the packages page', function () {
    $this->asAcademy($this->academy);
    $open = fn (string $student) => app(LessonPackages::class)->open([
        'student_id' => $student, 'label' => '1 hour', 'minutes_total' => 60,
        'price_minor' => 20000, 'currency' => 'EGP', 'bill_timing' => 'ON_START',
        'starts_on' => '2026-06-01', 'carry_over' => false,
    ], (string) $this->owner->id, 'ACADEMY_OWNER')['package_id'];
    $leftOpen = $open($this->leaving);
    $kept = $open($this->staying);
    $this->clearTenantContext();
    removeTheOldWay($this->leaving);

    Sanctum::actingAs($this->owner);
    $ids = fn (string $url) => collect($this->getJson($url)->assertOk()->json('packages'))->pluck('id')->all();
    foreach (['/api/packages', '/api/packages?scope=open', '/api/packages?scope=due'] as $url) {
        expect($ids($url))->toContain($kept)->not->toContain($leftOpen);
    }
    $this->getJson('/api/packages/summary')->assertOk()
        ->assertJsonPath('active', 1)->assertJsonPath('lowBalance', 1)->assertJsonPath('due', 1);
    // Hidden, not touched: still open, and a lookup by the student still finds it.
    expect($ids("/api/packages?student_id={$this->leaving}"))->toBe([$leftOpen]);
    $this->asAcademy($this->academy);
    expect(DB::table('lesson_packages')->where('id', $leftOpen)->value('status'))->toBe('ACTIVE');
});

it('lists what old removals left running, and winds it down with --apply', function () {
    $ghost = $this->createSession($this->academy, $this->leaving, $this->teacher, [
        'scheduled_at_utc' => '2026-06-08 10:00:00+00', 'status' => 'SCHEDULED',
    ]);
    $held = $this->createSession($this->academy, $this->leaving, $this->teacher, [
        'scheduled_at_utc' => '2026-04-08 10:00:00+00', 'status' => 'ATTENDED',
    ]);
    $this->asAcademy($this->academy);
    $scheduleId = (string) Str::uuid();
    DB::table('schedules')->insert([
        'id' => $scheduleId, 'academy_id' => $this->academy, 'student_id' => $this->leaving, 'teacher_id' => $this->teacher,
        'timezone' => 'Africa/Cairo', 'is_active' => true, 'created_at' => now(), 'updated_at' => now(),
    ]);
    DB::table('student_teacher_assignments')->insert([
        'id' => (string) Str::uuid(), 'academy_id' => $this->academy, 'student_id' => $this->leaving,
        'teacher_id' => $this->teacher, 'started_at' => '2026-03-01 00:00:00+00', 'created_at' => now(), 'updated_at' => now(),
    ]);
    $packageId = app(LessonPackages::class)->open([
        'student_id' => $this->leaving, 'label' => '10 hours', 'minutes_total' => 600,
        'price_minor' => 200000, 'currency' => 'EGP', 'bill_timing' => 'ON_START',
        'starts_on' => '2026-03-01', 'carry_over' => false,
    ], (string) $this->owner->id, 'ACADEMY_OWNER')['package_id'];
    $this->clearTenantContext();
    removeTheOldWay($this->leaving);

    // Dry run: listed, nothing changed.
    $this->artisan('students:finish-removal', ['--academy' => $this->academy])
        ->expectsOutputToContain('Leaving')
        ->assertSuccessful();
    $this->asAcademy($this->academy);
    expect(DB::table('sessions')->where('id', $ghost)->value('status'))->toBe('SCHEDULED');
    $this->clearTenantContext();

    $this->artisan('students:finish-removal', ['--academy' => $this->academy, '--apply' => true])->assertSuccessful();

    $this->asAcademy($this->academy);
    $ghostRow = DB::table('sessions')->where('id', $ghost)->first();
    expect($ghostRow->status)->toBe('CANCELLED_BY_STUDENT');
    expect($ghostRow->hidden_at)->not->toBeNull();
    // History is kept as it was — only hidden.
    expect(DB::table('sessions')->where('id', $held)->value('status'))->toBe('ATTENDED');
    expect(DB::table('sessions')->where('id', $held)->value('hidden_at'))->not->toBeNull();
    $schedule = DB::table('schedules')->where('id', $scheduleId)->first();
    expect($schedule->is_active)->toBeFalse();
    expect($schedule->deleted_at)->not->toBeNull();
    expect(DB::table('student_teacher_assignments')->where('student_id', $this->leaving)->whereNull('ended_at')->count())->toBe(0);
    // A paid block is a money decision: left open without --blocks.
    expect(DB::table('lesson_packages')->where('id', $packageId)->value('status'))->toBe('ACTIVE');
    expect(DB::table('audit_log')->where('action', 'student.removal_finished')->where('entity_id', $this->leaving)->exists())->toBeTrue();
    // The student who stays is untouched.
    expect(DB::table('students')->where('id', $this->staying)->value('deleted_at'))->toBeNull();
    $this->clearTenantContext();

    $this->artisan('students:finish-removal', ['--academy' => $this->academy, '--apply' => true, '--blocks' => true])->assertSuccessful();
    $this->asAcademy($this->academy);
    expect(DB::table('lesson_packages')->where('id', $packageId)->value('status'))->toBe('CANCELLED');
    $this->clearTenantContext();

    // Run again: nothing left.
    $this->artisan('students:finish-removal', ['--academy' => $this->academy])
        ->expectsOutputToContain('Nothing left running')
        ->assertSuccessful();
});
