/*
 * A removed student leaves nothing behind on the to-do surfaces: الحصص المعلقة, pending marking,
 * the notifications inbox + bell, the trials board, the student-report queue — and the
 * `students:finish-removal` repair finishes off students removed before the wind-down existed.
 */

uses(RefreshDatabase::class, InteractsWithTenancy::class, CreatesTenantData::class, CreatesAuthUsers::class);

beforeEach(function () {
    Carbon::setTestNow('2026-06-11 12:00:00');
    $this->seed(DemoAcademySeeder::class);
    $this->clearTenantContext();
    $pro = DB::table('plans')->where('code', 'PRO')->value('id');
    $this->academy = $this->createAcademy(overrides: ['default_currency' => 'EGP', 'plan_id' => $pro]);
    $this->owner = $this->makeUser($this->academy, 'ACADEMY_OWNER', ['email' => 'owner-leftovers@test.local']);
    $this->teacher = $this->createTeacher($this->academy, ['full_name' => 'Leftover Teacher']);
    $this->leaving = $this->createStudent($this->academy, overrides: ['full_name' => 'Leaving']);
    $this->staying = $this->createStudent($this->academy, overrides: ['full_name' => 'Staying']);
});

/** A student deleted the old way: the row soft-deleted, nothing else touched (before 2026-10-06). */
function removeTheOldWay(string $studentId, string $when = '2026-05-01 09:00:00+00'): void
{
    test()->asAcademy(test()->academy);
    DB::table('students')->where('id', $studentId)->update(['deleted_at' => $when]);
    test()->clearTenantContext();
}

function overdueIds(): array
{
    return collect(test()->getJson('/api/sessions/overdue')->assertOk()->json('sessions'))->pluck('id')->all();
}

it('keeps an old removed student\'s never-hidden lessons out of the waiting queues', function () {
    // Generated by a timetable that outlived its student, after the 10-19 backfill: never hidden.
    $ghost = $this->createSession($this->academy, $this->leaving, $this->teacher, [
        'scheduled_at_utc' => '2026-06-08 10:00:00+00', 'status' => 'SCHEDULED',
    ]);
    $real = $this->createSession($this->academy, $this->staying, $this->teacher, [
        'scheduled_at_utc' => '2026-06-08 12:00:00+00', 'status' => 'SCHEDULED',
    ]);
    removeTheOldWay($this->leaving);

    Sanctum::actingAs($this->owner);
    $overdue = $this->getJson('/api/sessions/overdue')->assertOk();
    expect(collect($overdue->json('sessions'))->pluck('id')->all())->toContain($real)->not->toContain($ghost);
    expect($overdue->json('count'))->toBe(1);
    expect(collect($this->getJson('/api/sessions/pending-attendance')->json('sessions'))->pluck('id')->all())
        ->toContain($real)->not->toContain($ghost);
});

it('cancels a trial still booked for the student when they are deleted', function () {
    $this->asAcademy($this->academy);
    $trialId = (string) Str::uuid();
    DB::table('trials')->insert([
        'id' => $trialId, 'academy_id' => $this->academy, 'teacher_id' => $this->teacher, 'student_id' => $this->leaving,
        'timezone' => 'Africa/Cairo', 'scheduled_at_utc' => '2026-06-13 10:00:00+00', 'duration_minutes' => 30,
        'status' => 'SCHEDULED', 'created_at' => now(), 'updated_at' => now(),
    ]);
    $this->clearTenantContext();

    Sanctum::actingAs($this->owner);
    $this->deleteJson("/api/students/{$this->leaving}")->assertOk();

    $this->asAcademy($this->academy);
    expect(DB::table('trials')->where('id', $trialId)->value('status'))->toBe('CANCELLED');
});

it('takes the student\'s alerts off the notifications page and the bell', function () {
    $lesson = $this->createSession($this->academy, $this->leaving, $this->teacher, [
        'scheduled_at_utc' => '2026-06-09 10:00:00+00', 'status' => 'ATTENDED',
    ]);
    $otherLesson = $this->createSession($this->academy, $this->staying, $this->teacher, [
        'scheduled_at_utc' => '2026-06-09 12:00:00+00', 'status' => 'ATTENDED',
    ]);
    $this->asAcademy($this->academy);
    $alert = fn (array $row) => DB::table('notifications')->insert($row + [
        'id' => (string) Str::uuid(), 'academy_id' => $this->academy, 'audience_role' => 'ACADEMY_OWNER',
        'created_at' => now()->toIso8601String(),
    ]);
    // An overdue-report alert on their lesson, a package alert naming them, and one for someone staying.
    $alert(['type' => 'REPORT_OVERDUE', 'category' => 'REPORTS', 'session_id' => $lesson, 'data' => json_encode(['student_name' => 'Leaving'])]);
    $alert(['type' => 'PACKAGE_LOW', 'category' => 'PACKAGES', 'subject_id' => (string) Str::uuid(), 'data' => json_encode(['student_id' => $this->leaving])]);
    $alert(['type' => 'REPORT_OVERDUE', 'category' => 'REPORTS', 'session_id' => $otherLesson, 'data' => json_encode(['student_name' => 'Staying'])]);
    $this->clearTenantContext();

    Sanctum::actingAs($this->owner);
    expect($this->getJson('/api/notifications/summary')->assertOk()->json('reports'))->toBe(2);

    $this->deleteJson("/api/students/{$this->leaving}")->assertOk();

    $summary = $this->getJson('/api/notifications/summary')->assertOk();
    expect($summary->json('reports'))->toBe(1);
    expect($summary->json('packages'))->toBe(0);
    $listed = collect($this->getJson('/api/notifications')->assertOk()->json('notifications'));
    // Only the staying student's alert is left — the package alert naming them went too.
    expect($listed->pluck('session_id')->all())->toBe([$otherLesson]);
});

it('raises no "package ended" alert when the package closes because the student was removed', function () {
    $this->asAcademy($this->academy);
    $packageId = app(LessonPackages::class)->open([
        'student_id' => $this->leaving, 'label' => '10 hours', 'minutes_total' => 600,
        'price_minor' => 200000, 'currency' => 'EGP', 'bill_timing' => 'ON_START',
        'starts_on' => '2026-06-01', 'carry_over' => false,
    ], (string) $this->owner->id, 'ACADEMY_OWNER')['package_id'];
    DB::table('lesson_packages')->where('id', $packageId)->update(['minutes_consumed' => 60]);
    $this->clearTenantContext();

    Sanctum::actingAs($this->owner);
    $this->deleteJson("/api/students/{$this->leaving}")->assertOk();

    $this->asAcademy($this->academy);
    expect(DB::table('lesson_packages')->where('id', $packageId)->value('status'))->toBe('COMPLETED');
    expect(DB::table('notifications')->where('type', 'PACKAGE_COMPLETED')->where('subject_id', $packageId)->exists())->toBeFalse();
});

